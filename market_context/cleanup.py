NOT_SAME_COMPANY = set()   # settled cases now live in NEVER_MERGE_KEYS above

def edit_dist(a, b):
    """Levenshtein. Used to decide 'one obvious typo' per Ray's Sept 8 rule."""
    if a == b: return 0
    if abs(len(a) - len(b)) > 1: return 2
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]

