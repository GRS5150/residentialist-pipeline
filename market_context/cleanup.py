for cat, counter in percat.items():
    if cat.lower() in ("windows", "window", "appliances"): continue
    clusters = collections.defaultdict(list)
    for brand, n in counter.items(): clusters[norm_key(brand)].append((brand, n))
    for key, members in clusters.items():
        if len(members) < 2: continue
        members.sort(key=lambda x: -x[1])
        canon = members[0][0]
        al = [b for b, _ in members if b != canon]
        if al: generated[f"{canon}|{cat}"] = sorted(al)
    if cat in TARGET_CATS:
        keys = sorted(clusters, key=lambda k: -sum(n for _, n in clusters[k]))[:150]
        # union-find so chains (a~b, b~c) collapse to one canonical, not a chain
        parent = {k: k for k in keys}
        def find(x):
            while parent[x] != x:
                parent[x] = parent[parent[x]]; x = parent[x]
            return x
        def union(x, y):
            rx, ry = find(x), find(y)
            if rx != ry: parent[ry] = rx
        for i, x in enumerate(keys):
            for y in keys[i + 1:]:
                if not x or not y or abs(len(x) - len(y)) > 1: continue
                if x in NEVER_MERGE_KEYS or y in NEVER_MERGE_KEYS: continue
                if edit_dist(x, y) > 1: continue
                if min(len(x), len(y)) < 6: continue
                nx = sum(n for _, n in clusters[x]); ny = sum(n for _, n in clusters[y])
                bx = max(clusters[x], key=lambda t: t[1])[0]
                by = max(clusters[y], key=lambda t: t[1])[0]
                if frozenset((x, y)) in NOT_SAME_COMPANY:
                    big, small = (bx, by) if nx >= ny else (by, bx)
                    flagged.append({"category": cat, "canonical": big, "variant": small,
                                    "canonical_count": max(nx, ny), "variant_count": min(nx, ny),
                                    "reason": "one edit apart but plausibly two different companies"})
                    continue
                union(x, y)
        groups = collections.defaultdict(list)
        for k in keys: groups[find(k)].append(k)
        for root, members in groups.items():
            if len(members) < 2: continue
            spellings = [(b, n) for k in members for b, n in clusters[k]]
            # canonical: authority list first, else most frequent then fuller
            canon = None
            for k in members:
                if k in AUTHORITY_BY_KEY:
                    canon = AUTHORITY_BY_KEY[k]; break
            if canon is None:
                canon = sorted(spellings, key=lambda t: (-t[1], -len(t[0]), t[0]))[0][0]
